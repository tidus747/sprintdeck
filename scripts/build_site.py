"""Build the public documentation from an explicit, session-free source list."""

import argparse
import html
from html.parser import HTMLParser
import json
from pathlib import Path
import re
import shutil
from string import Template
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parents[1]
REPOSITORY = "https://github.com/tidus747/sprintdeck"
PUBLIC_URL = "https://tidus747.github.io/sprintdeck"
PAGES = [
    ("getting-started", "README.md", "Getting started", "Start here"),
    ("scenes", "docs/scenes.md", "Scenes and screenshots", "Start here"),
    ("obs-setup", "docs/obs-setup.md", "OBS setup", "Start here"),
    ("configuration", "docs/configuration.md", "Configuration", "Using SprintDeck"),
    ("session-recap", "docs/session-recap.md", "Notes and recap", "Using SprintDeck"),
    ("privacy", "docs/privacy.md", "Privacy and local data", "Using SprintDeck"),
    ("architecture", "docs/architecture.md", "Architecture and API", "Development"),
    ("verification", "docs/verification.md", "Verification", "Development"),
    ("roadmap", "docs/roadmap.md", "Project roadmap", "Development"),
    ("website", "docs/website.md", "Documentation website", "Development"),
    ("contributing", "CONTRIBUTING.md", "Contributing", "Project"),
    ("contributors", "CONTRIBUTORS.md", "Contributors", "Project"),
    ("changelog", "CHANGELOG.md", "Changelog", "Project"),
    ("agent-guidelines", "AGENTS.md", "Agent guidelines", "Project"),
    ("license", "LICENSE", "License", "Project"),
]


def pages():
    result = list(PAGES)
    known = {source for _, source, _, _ in result}
    for path in sorted((ROOT / "docs").glob("*.md")):
        source = path.relative_to(ROOT).as_posix()
        if source not in known:
            result.append((path.stem, source, path.stem.replace("-", " ").title(), "Development"))
    return result


class RewriteLinks(HTMLParser):
    def __init__(self, source, base, routes):
        super().__init__(convert_charrefs=False)
        self.source, self.base, self.routes = source, base, routes
        self.parts = []

    def url(self, value):
        parsed = urlsplit(value)
        if parsed.scheme or parsed.netloc or not parsed.path:
            return value
        target = (self.source.parent / parsed.path).resolve()
        suffix = ("?" + parsed.query if parsed.query else "") + ("#" + parsed.fragment if parsed.fragment else "")
        if target in self.routes:
            return self.base + "/docs/" + self.routes[target] + "/" + suffix
        if target == ROOT / "examples/demo-session.json":
            return self.base + "/downloads/demo-session.json" + suffix
        asset_root = ROOT / "website/assets"
        if target.is_relative_to(asset_root):
            return self.base + "/assets/" + target.relative_to(asset_root).as_posix() + suffix
        if target.is_relative_to(ROOT) and target.is_file():
            return REPOSITORY + "/blob/main/" + target.relative_to(ROOT).as_posix() + suffix
        raise ValueError(f"Unresolved documentation link in {self.source.relative_to(ROOT)}: {value}")

    def handle_starttag(self, tag, attrs):
        rewritten = []
        for name, value in attrs:
            if value is not None and name in ("href", "src"):
                value = self.url(value)
            rewritten.append(name if value is None else f'{name}="{html.escape(value, quote=True)}"')
        self.parts.append("<" + tag + (" " + " ".join(rewritten) if rewritten else "") + ">")

    def handle_startendtag(self, tag, attrs):
        self.handle_starttag(tag, attrs)

    def handle_endtag(self, tag):
        self.parts.append(f"</{tag}>")

    def handle_data(self, data):
        self.parts.append(data)

    def handle_entityref(self, name):
        self.parts.append(f"&{name};")

    def handle_charref(self, name):
        self.parts.append(f"&#{name};")


class PlainText(HTMLParser):
    def __init__(self):
        super().__init__()
        self.parts = []

    def handle_data(self, data):
        self.parts.append(data)


def build(output, base="/sprintdeck"):
    import markdown
    if base and (not re.fullmatch(r"/[A-Za-z0-9_/-]+", base) or ".." in base):
        raise ValueError("Base path must be empty or an absolute URL path without parent segments")
    base = base.rstrip("/")
    output = Path(output).resolve()
    marker = output / ".sprintdeck-generated-site"
    if output == ROOT or output in ROOT.parents:
        raise ValueError("Output must not overwrite the repository or one of its parents")
    if output.exists() and any(output.iterdir()):
        if not marker.is_file() or marker.read_text(encoding="utf-8") != "SprintDeck public documentation\n":
            raise ValueError("Refusing to replace an output directory not generated by SprintDeck")
        # The resolved target and ownership marker have been checked before recursive removal.
        shutil.rmtree(output)
    output.mkdir(parents=True)
    marker.write_text("SprintDeck public documentation\n", encoding="utf-8")
    documents = pages()
    routes = {(ROOT / source).resolve(): slug for slug, source, _, _ in documents}
    shell = Template((ROOT / "website/templates/page.html").read_text(encoding="utf-8"))
    home = Template((ROOT / "website/templates/home.html").read_text(encoding="utf-8"))
    common = {"BASE": base, "REPOSITORY": REPOSITORY}
    (output / "index.html").write_text(home.substitute(common), encoding="utf-8")
    index = []
    for slug, source, title, group in documents:
        path = ROOT / source
        text = path.read_text(encoding="utf-8")
        converter = markdown.Markdown(extensions=["fenced_code", "tables", "toc", "sane_lists"], output_format="html")
        content = "<h1 id=\"license\">GNU General Public License v3</h1><pre>" + html.escape(text) + "</pre>" if source == "LICENSE" else converter.convert(text)
        rewrite = RewriteLinks(path, base, routes)
        rewrite.feed(content)
        navigation, current_group = [], None
        for link_slug, _, link_title, link_group in documents:
            if link_group != current_group:
                navigation.append(f'<p class="nav-group">{html.escape(link_group)}</p>')
                current_group = link_group
            current = ' aria-current="page"' if link_slug == slug else ""
            navigation.append(f'<a href="{base}/docs/{link_slug}/"{current}>{html.escape(link_title)}</a>')
        target = output / "docs" / slug
        target.mkdir(parents=True)
        target.joinpath("index.html").write_text(shell.substitute(common, TITLE=html.escape(title),
            GROUP=html.escape(group), CONTENT="".join(rewrite.parts), NAVIGATION="".join(navigation),
            TOC=converter.toc, SOURCE=REPOSITORY + "/blob/main/" + source), encoding="utf-8")
        plain = PlainText(); plain.feed(content)
        index.append({"title": title, "group": group, "url": f"{base}/docs/{slug}/", "text": " ".join(plain.parts)})
    shutil.copytree(ROOT / "website/assets", output / "assets")
    (output / "assets/search-index.json").write_text(json.dumps(index, ensure_ascii=True), encoding="utf-8")
    (output / "downloads").mkdir()
    shutil.copyfile(ROOT / "examples/demo-session.json", output / "downloads/demo-session.json")
    (output / ".nojekyll").touch()
    urls = [PUBLIC_URL + "/"] + [PUBLIC_URL + "/docs/" + slug + "/" for slug, _, _, _ in documents]
    sitemap = '<?xml version="1.0" encoding="UTF-8"?><urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">' + "".join(f"<url><loc>{html.escape(url)}</loc></url>" for url in urls) + "</urlset>"
    (output / "sitemap.xml").write_text(sitemap, encoding="utf-8")
    print(f"Built homepage and {len(documents)} documentation pages in {output.name}/ (base: {base or '/'})")
    return output


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=ROOT / "_site")
    parser.add_argument("--base", default="/sprintdeck", help="GitHub Pages repository path, or empty for local root preview")
    args = parser.parse_args()
    try:
        build(args.output, args.base)
    except ImportError:
        parser.exit(1, "Install the documentation-only dependencies: python -m pip install --require-hashes -r website/requirements.txt\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
